"""Builds src/lib/rules/packs/marketing-en.json from MIT-licensed third-party rule sets.

Sources (cloned into ./reference, which is git-ignored):
  - tbhb/vale-ai-tells          (MIT, (c) 2025-2026 Tony Burns)       Vale "existence" rules
  - cagatayuncu/marketing-machine (MIT, (c) 2026 Cagatay Uncu)        rules/lang.en.json regex rules

Only rules that make sense for marketing copy are taken, and each is mapped to one of our finding
categories with a severity. Confidence is always "medium": these are wording heuristics, not facts,
so a reviewer can dismiss them and the score impact stays small (proposal 7.4, 10.4).

Run:  python -I scripts/build-rulepack.py reference src/lib/rules/packs/marketing-en.json
"""
import json
import pathlib
import sys

import yaml

ref = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])

VALE = "tbhb/vale-ai-tells (MIT)"
MM = "cagatayuncu/marketing-machine (MIT)"

# (file, code, category, severity, why)
VALE_RULES = [
    ("ai-tells/AbsoluteAssertions", "PACK-ABSOLUTE", "claim", "minor", "An absolute claim needs evidence or a softer wording."),
    ("ai-tells/UniversalObject", "PACK-TOTALITY", "claim", "minor", "Claims of covering every case are rarely provable."),
    ("ai-tells/VagueAttributions", "PACK-VAGUE-SOURCE", "claim", "minor", "A claim attributed to unnamed studies or experts is unsupported."),
    ("ai-tells-commits/CommitUnquantifiedClaims", "PACK-UNQUANTIFIED", "claim", "minor", "A performance claim without a number and baseline is unsupported."),
    ("ai-tells/PromotionalPuffery", "PACK-PUFFERY", "tone", "minor", "Promotional puffery weakens trust and is not specific."),
    ("ai-tells/StrategyBuzzwords", "PACK-BUZZWORD", "tone", "minor", "Buzzwords hide the actual benefit."),
    ("ai-tells/UrgencyInflation", "PACK-URGENCY", "tone", "minor", "Inflated urgency reads as pressure selling."),
    ("ai-tells/FalseExclusivity", "PACK-EXCLUSIVITY", "tone", "minor", "Claims of insider knowledge are not a reason to believe the point."),
    ("ai-tells/OpeningCliches", "PACK-OPENING", "tone", "minor", "A generic opening delays the actual message."),
    ("ai-tells/OverusedVocabulary", "PACK-AI-VOCAB", "tone", "info", "Vocabulary often overused in AI-generated text; common in human writing too, so it is shown as information only."),
    ("ai-tells-commits/CommitMarketingAdjectives", "PACK-HYPE-ADJ", "tone", "minor", "Hype adjectives say nothing measurable."),
]

# marketing-machine rule id -> (code, category, severity)
MM_RULES = {
    "en-hype": ("PACK-HYPE", "tone", "minor"),
    "en-flawless": ("PACK-FLAWLESS", "claim", "major"),
    "en-empty-verb": ("PACK-EMPTY-VERB", "tone", "minor"),
    "en-unmeasured-speed": ("PACK-UNMEASURED-SPEED", "claim", "minor"),
    "en-unmeasured-gain": ("PACK-UNMEASURED-GAIN", "claim", "major"),
    "en-legal-compliance-claim": ("PACK-COMPLIANCE-CLAIM", "claim", "major"),
    "en-absolute-claim": ("PACK-ABSOLUTE-NEGATIVE", "claim", "minor"),
}


def vale_pattern(rule: dict) -> tuple[str, bool]:
    """Returns (regex source, ignorecase). Vale tokens are alternatives; raw is concatenated."""
    ignorecase = bool(rule.get("ignorecase"))
    if "raw" in rule:
        src = "".join(rule["raw"])
        if src.startswith("(?i)"):
            src, ignorecase = src[4:], True
        return src, ignorecase
    tokens = [str(t) for t in rule.get("tokens", [])]
    alt = "|".join(f"(?:{t})" for t in tokens)
    if rule.get("nonword"):
        return f"(?:{alt})", ignorecase
    return rf"(?<![\p{{L}}\p{{N}}])(?:{alt})(?![\p{{L}}\p{{N}}])", ignorecase


rules = []
for path, code, category, severity, why in VALE_RULES:
    data = yaml.safe_load((ref / "vale-ai-tells/styles" / f"{path}.yml").read_text(encoding="utf8"))
    assert data["extends"] == "existence", path
    pattern, ignorecase = vale_pattern(data)
    message = data["message"].replace("AI commit tell: ", "").replace("'%s'", "").replace("  ", " ")
    rules.append(dict(code=code, category=category, severity=severity, pattern=pattern, ignoreCase=ignorecase,
                      message=message.strip(), why=why, fix=None, source=f"{VALE} styles/{path}.yml"))

mm = json.loads((ref / "marketing-machine/rules/lang.en.json").read_text(encoding="utf8"))
for r in mm["rules"]:
    if r["id"] not in MM_RULES:
        continue
    code, category, severity = MM_RULES[r["id"]]
    rules.append(dict(code=code, category=category, severity=severity,
                      pattern=rf"(?<![\p{{L}}\p{{N}}])(?:{r['pattern']})(?![\p{{L}}\p{{N}}])", ignoreCase=True,
                      message=r["why"], why=r["why"], fix=r.get("fix"), source=f"{MM} rules/lang.en.json#{r['id']}"))

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps({
    "$comment": "Generated by scripts/build-rulepack.py from MIT-licensed rule sets; see LICENSES.md. Do not edit by hand.",
    "rules": rules,
}, indent=1, ensure_ascii=False) + "\n", encoding="utf8")
print(f"wrote {len(rules)} rules to {out}")
